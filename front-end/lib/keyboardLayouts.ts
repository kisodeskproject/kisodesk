const DEAD_KEY_MARKS = {
  acute: { combiningMark: '\u0301', standaloneMark: '´' },
  grave: { combiningMark: '\u0300', standaloneMark: '`' },
  diaeresis: { combiningMark: '\u0308', standaloneMark: '¨' },
  circumflex: { combiningMark: '\u0302', standaloneMark: '^' },
  tilde: { combiningMark: '\u0303', standaloneMark: '~' },
  caron: { combiningMark: '\u030C', standaloneMark: 'ˇ' },
  abovering: { combiningMark: '\u030A', standaloneMark: '˚' },
} as const;

type DeadKeyMark = keyof typeof DEAD_KEY_MARKS;

function makeDeadKey(
  physicalKeyId: string,
  shiftKey: boolean,
  mark: DeadKeyMark,
): DeadKeyDefinition {
  return { physicalKeyId: physicalKeyId as PhysicalKeyId, shiftKey, ...DEAD_KEY_MARKS[mark] };
}

