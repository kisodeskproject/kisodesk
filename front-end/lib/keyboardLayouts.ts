export function getDefaultLayoutForLocale(locale?: string | null): KeyboardLayout {
  const canonicalLocale = locale?.trim() ?? '';
  const matchedLayout = getEnabledLayouts().find((layout) =>
    layout.languageCodes.some((languageCode) =>
      canonicalLocale.toLowerCase().startsWith(languageCode.toLowerCase()),
    ),
  );
  if (matchedLayout) return matchedLayout;
  return getDefaultLayoutForLanguage(canonicalLocale.split('-')[0].toLowerCase());
}
