export function getKeyOutput(
  layout: KeyboardLayout,
  physicalKeyId: PhysicalKeyId,
  shiftKey = false,
  altGrKey = false,
): string | undefined {
  if (altGrKey) {
    const altGrOutput = shiftKey
      ? layout.shiftAltGrKeys?.[physicalKeyId]
      : layout.altGrKeys?.[physicalKeyId];
    if (altGrOutput !== undefined) return altGrOutput;
  }
  const baseOutput = layout.keys[physicalKeyId];
  if (!shiftKey) return baseOutput;

  const explicitShiftOutput = layout.shiftedKeys?.[physicalKeyId];
  if (explicitShiftOutput !== undefined) return explicitShiftOutput;

  if (baseOutput && /^\p{L}$/u.test(baseOutput)) {
    if (layout.id === 'qwerty-tr') {
      if (baseOutput === 'i') return 'İ';
      if (baseOutput === 'ı') return 'I';
    }
    return baseOutput.toUpperCase();
  }

  return baseOutput;
}

export function getDeadKey(
  layout: KeyboardLayout,
  physicalKeyId: PhysicalKeyId,
  shiftKey: boolean,
): DeadKeyDefinition | undefined {
  return layout.deadKeys?.find(
    (deadKey) => deadKey.physicalKeyId === physicalKeyId && deadKey.shiftKey === shiftKey,
  );
}

export const getEnabledLayouts = (): KeyboardLayout[] =>
  KEYBOARD_LAYOUTS.filter((layout) => layout.enabled);

export function layoutSupportsLocale(
  layout: KeyboardLayout,
  locale: KeyboardContentLanguage | Locale | string | null | undefined,
): boolean {
  if (!locale) return false;
  const normalizedLocale = locale.toLowerCase();

  return layout.languageCodes.some((languageCode) => {
    const normalizedLanguageCode = languageCode.toLowerCase();
    return (
      normalizedLanguageCode === normalizedLocale ||
      (!normalizedLocale.includes('-') && normalizedLanguageCode.startsWith(`${normalizedLocale}-`))
    );
  });
}

function getLayoutPhysicalKeyIds(layout: KeyboardLayout): PhysicalKeyId[] {
  return Array.from(
    new Set<PhysicalKeyId>([
      ...(Object.keys(layout.keys) as PhysicalKeyId[]),
      ...(Object.keys(layout.shiftedKeys ?? {}) as PhysicalKeyId[]),
      ...(Object.keys(layout.altGrKeys ?? {}) as PhysicalKeyId[]),
      ...(Object.keys(layout.shiftAltGrKeys ?? {}) as PhysicalKeyId[]),
      ...(layout.deadKeys?.map((deadKey) => deadKey.physicalKeyId) ?? []),
    ]),
  );
}

export function getKeyboardLayoutCompatibility(
  layout: KeyboardLayout,
  physicalFamily: KeyboardPhysicalFamily,
): KeyboardLayoutCompatibility {
  const missingPhysicalKeyIds = getLayoutPhysicalKeyIds(layout).filter(
    (physicalKeyId) => !physicalFamilyHasKeyId(physicalFamily, physicalKeyId),
  );

  return {
    layout,
    compatible: missingPhysicalKeyIds.length === 0,
    missingPhysicalKeyIds,
    preferredForPhysicalFamily: layout.physicalType === physicalFamily,
  };
}

export function getEnabledLayoutsForLocale(
  locale: KeyboardContentLanguage | Locale | string | null | undefined,
  physicalFamily: KeyboardPhysicalFamily,
): KeyboardLayoutCompatibility[] {
  return getEnabledLayouts()
    .filter((layout) => layoutSupportsLocale(layout, locale))
    .map((layout) => getKeyboardLayoutCompatibility(layout, physicalFamily))
    .sort(
      (left, right) =>
        Number(right.compatible) - Number(left.compatible) ||
        Number(right.preferredForPhysicalFamily) - Number(left.preferredForPhysicalFamily) ||
        left.layout.name.localeCompare(right.layout.name),
    );
}
