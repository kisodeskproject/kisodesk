export function resolveKeyboardLayout({
  layoutId,
  language,
}: {
  layoutId?: string | null;
  language?: string | null;
}): KeyboardLayout {
  return (
    getEnabledLayouts().find((layout) => layout.id === layoutId) ??
    getDefaultLayoutForLanguage(language)
  );
}
