function explanatory({
  slug,
  title,
  description,
  objective,
  content,
  order,
  audioUrl = null,
  instructions = 'Escucha con atención y continúa cuando estés listo.',
}) {
  return {
    slug,
    title,
    description,
    objective,
    content,
    type: 'explanatory',
    instructions,
    focusKeys: [],
    reviewKeys: [],
    allowedCharacters: [],
    targetKeys: [],
    difficulty: 1,
    estimatedSeconds: 35,
    minAccuracy: 100,
    maxTargetKeyErrors: 0,
    requiredSuccessfulAttempts: 1,
    hideLiveWpm: true,
    mediaUrl: null,
    audioUrl,
    required: true,
    order,
  };
}

function practice({
  slug,
  title,
  description,
  objective,
  content,
  order,
  audioUrl = null,
  instructions = 'Escribe las frases en inglés con calma y precisión.',
}) {
  return {
    slug,
    title,
    description,
    objective,
    content,
    type: 'practice',
    instructions,
    focusKeys: characters(content.replace(/[^a-zA-Z]/g, '').toLowerCase()),
    reviewKeys: [],
    allowedCharacters: characters(content),
    targetKeys: [],
    difficulty: 1,
    estimatedSeconds: 45,
    minAccuracy: 90,
    maxTargetKeyErrors: 3,
    requiredSuccessfulAttempts: 1,
    hideLiveWpm: false,
    mediaUrl: null,
    audioUrl,
    required: true,
    order,
  };
}

